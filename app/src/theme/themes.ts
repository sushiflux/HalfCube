const byKey = new Map<ThemeKey, Theme>(themes.map((t) => [t.key, t]));

export function isThemeKey(value: unknown): value is ThemeKey {
  return typeof value === "string" && byKey.has(value as ThemeKey);
}

export function isMode(value: unknown): value is Mode {
  return value === "light" || value === "dark";
}

export function getTheme(key: ThemeKey): Theme {
  const theme = byKey.get(key);
  if (!theme) throw new Error(`Unknown theme "${key}".`);
  return theme;
}
