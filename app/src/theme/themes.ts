// Colour themes: seven themes, each in light and dark. Generated once from the owner's theme table; edit the values
// here from now on. Every value is a token that reaches the UI as a CSS custom property (see css.ts), components never
// carry their own colours.

/** Colour tokens of one theme in one mode. */
export const colourTokenNames = ["bg","surface","surface2","line","lineStrong","text","muted","primary","onPrimary","primarySoft","create","onCreate","destructive","onDestructive","toggleOn","toggleOff","accent1","accent2","viewport","viewport2","faceTop","faceLeft","faceRight","sketchUnder","sketchFull","sketchOver","construction","centre","dimLine","dimText","constraint","projected","profileFill","bodyEdge","silhouette","hiddenEdge","gridMajor","gridMinor","axisX","axisY","axisZ","plane","selection","hover","error"] as const;
export type ColourTokenName = (typeof colourTokenNames)[number];
export type ColourTokens = Record<ColourTokenName, string>;

/** Line types that carry a weight (px at the 1600 x 900 design size) and a dash pattern ("" = solid). */
export const lineTypeNames = ["sketchUnder","sketchFull","sketchOver","construction","centre","dimLine","constraint","projected","bodyEdge","silhouette","hiddenEdge","gridMajor","gridMinor","axisX","axisY","axisZ","plane","selection","hover","error"] as const;
export type LineTypeName = (typeof lineTypeNames)[number];

/** Fill opacities that differ per theme. */
export const opacityNames = ["profileFill","plane","selection","hover"] as const;
export type OpacityName = (typeof opacityNames)[number];

export const themeKeys = ["praezision","skizze","graphit","blaupause","kontrast","farbsicher","daemmerung"] as const;
export type ThemeKey = (typeof themeKeys)[number];

export type Mode = "light" | "dark";
export const modes: readonly Mode[] = ["light", "dark"];

export interface Theme {
  key: ThemeKey;
  /** German name; the localized names live in the message catalogues. */
  name: string;
  isDefault: boolean;
  /** Stricter contrast targets (7:1 text, 4.5:1 everything else). */
  highContrast: boolean;
  /** Uses blue/orange instead of red/green for paired states. */
  colourSafe: boolean;
  weights: Record<LineTypeName, number>;
  dashes: Record<LineTypeName, string>;
  opacity: Record<OpacityName, number>;
  tokens: Record<Mode, ColourTokens>;
}

